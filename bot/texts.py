def format_result(res: dict, lang: str) -> tuple[str, str | None]:
    """API жауабы → (негізгі хабарлама, кеңес хабарламасы | None). HTML parse_mode."""
    t = T[lang]
    if res.get("reason") == "not_plant":
        return t["not_plant"], None
    top = res["top"][0]
    a = res["advice"]
    lines = [f"<b>{escape(a['title'])}</b> — {t['sev'][a['severity']]}",
             f"{t['conf']}: {round(top['prob'] * 100)}%"]
    if res.get("affected_pct") is not None and a["severity"] != "none":
        lines.append(f"{round(res['affected_pct'])}% {t['affected']}")
    if res.get("unsure"):
        lines.append("\n" + t["low_conf"])
        alts = ", ".join(f"{escape(x['name'])} {round(x['prob'] * 100)}%" for x in res["top"][1:])
        lines.append(f"{t['alts']}: {alts}")
    main = "\n".join(lines)
    adv = f"<b>{t['actions']}</b>\n{escape(a['actions']['agro'])}"
    if a["severity"] != "none":
        adv += f"\n\n<b>{t['chemical']}</b>\n{escape(a['actions']['chemical'])}"
        if a["timing"] != "—":
            adv += f"\n\n<b>{t['timing']}</b>\n{escape(a['timing'])}"
    adv += f"\n\n<i>{t['disclaimer']}</i>"
    return main, adv


def format_alert(a: dict) -> str:
    """POST /api/bot/alerts/poll жазбасы → бір хабарлама (ең көбі 10 ошақ)."""
    t = T[a["lang"]]
    lines = [t["alert"].format(r=round(a["radius_km"]))]
    for c in a["cases"][:10]:
        lines.append(t["alert_line"].format(name=escape(c["name"]), km=c["distance_km"], date=c["date"]))
    if len(a["cases"]) > 10:
        lines.append(f"… +{len(a['cases']) - 10}")
    lines.append("\n" + t["alert_tip"])
    return "\n".join(lines)


def format_history(rows: list[dict], lang: str, limit: int = 10) -> str:
    t = T[lang]
    if not rows:
        return t["history_empty"]
    out = [t["history_head"]]
    for r in rows[:limit]:
        field = f" · {escape(r['field'])}" if r.get("field") else ""
        out.append(f"{r['date'][:10]}{field} — {escape(r['name'])} ({round(r['confidence'] * 100)}%)")
    return "\n".join(out)


def format_reminder(r: dict) -> str:
    t = T[r["lang"]]
    field = f"{escape(r['field'])}: " if r.get("field") else ""
    return t["remind"].format(field=field, name=escape(r["name"]))
