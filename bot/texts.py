def format_result(res: dict, lang: str) -> tuple[str, str | None]:
    """API жауабы → (негізгі хабарлама, кеңес хабарламасы | None). HTML parse_mode."""
    t = T[lang]
    if res.get("reason") == "not_plant":
        return t["not_plant"], None
    top = res["top"][0]
    a = res["advice"]
    lines = [f"<b>{escape(a['title'])}</b> — {t['sev'][a['severity']]}",
             f"{t['conf']}: {round(top['prob'] * 100)}%"]
    if res.get("affected_pct") is not None and a["severity"] != "none":
        lines.append(f"{round(res['affected_pct'])}% {t['affected']}")
    if res.get("unsure"):
        lines.append("\n" + t["low_conf"])
        alts = ", ".join(f"{escape(x['name'])} {round(x['prob'] * 100)}%" for x in res["top"][1:])
        lines.append(f"{t['alts']}: {alts}")
    main = "\n".join(lines)
    adv = f"<b>{t['actions']}</b>\n{escape(a['actions']['agro'])}"
    if a["severity"] != "none":
        adv += f"\n\n<b>{t['chemical']}</b>\n{escape(a['actions']['chemical'])}"
        if a["timing"] != "—":
            adv += f"\n\n<b>{t['timing']}</b>\n{escape(a['timing'])}"
    adv += f"\n\n<i>{t['disclaimer']}</i>"
    return main, adv
